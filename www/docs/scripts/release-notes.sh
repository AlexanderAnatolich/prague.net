#!/usr/bin/env bash
# Generates the docs' "Release notes" page from the GitHub Releases of nanov/prague.net.
#
#   www/docs/scripts/release-notes.sh [output-path]
#
# Default output: www/docs/articles/reference/release-notes.md (gitignored — never commit it;
# the page is regenerated on every docs build). Needs only bash and python3 (standard library).
#
# Auth: GH_TOKEN is used when set. In CI pass `GH_TOKEN: ${{ github.token }}`; locally
# `GH_TOKEN=$(gh auth token --user nanov) www/docs/scripts/release-notes.sh`. Without a token the
# call is anonymous (public repo), which GitHub rate-limits to 60 requests per hour per IP.
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
out=${1:-"$here/../articles/reference/release-notes.md"}
repo=${PRAGUE_RELEASES_REPO:-nanov/prague.net}

mkdir -p "$(dirname "$out")"

python3 -I - "$repo" "$out" <<'PY'
import json
import os
import re
import sys
import urllib.error
import urllib.request

repo, out = sys.argv[1], sys.argv[2]
api = f"https://api.github.com/repos/{repo}/releases"
headers = {
    "Accept": "application/vnd.github+json",
    "X-GitHub-Api-Version": "2022-11-28",
    "User-Agent": "prague-docs-release-notes",
}
token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
if token:
    headers["Authorization"] = f"Bearer {token}"


def fetch_all():
    releases, page = [], 1
    while True:
        req = urllib.request.Request(f"{api}?per_page=100&page={page}", headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                batch = json.load(resp)
                link = resp.headers.get("Link", "")
        except urllib.error.HTTPError as e:
            sys.exit(f"release-notes: GitHub API {e.code} for {req.full_url}: {e.read().decode(errors='replace')[:300]}")
        releases.extend(batch)
        if 'rel="next"' not in link:
            return releases
        page += 1


TAG = re.compile(r"^v?(\d+)\.(\d+)\.(\d+)(?:-pre\.(\d+))?$")


def semver_key(tag):
    m = TAG.match(tag)
    if not m:
        return None
    major, minor, patch, pre = m.groups()
    # A stable version sorts above every prerelease of the same base (pre is None -> rank 1).
    return (int(major), int(minor), int(patch), 1 if pre is None else 0, int(pre or 0))


ATX = re.compile(r"^(#{1,6})[ \t]+(.*?)[ \t#]*$")
FENCE = re.compile(r"^[ \t]{0,3}(`{3,}|~{3,})")
DASHES = re.compile(r"^[ \t]*-{3,}[ \t]*$")
EQUALS = re.compile(r"^[ \t]*={3,}[ \t]*$")


def demote(body):
    """Release bodies are embedded as-is, except: headings move below the page's H1 and the
    per-release H2 (level = max(level + 1, 3)), a line of dashes/equals can neither open a YAML
    header nor turn the line above into a setext heading, and HTML comments are dropped. Fenced
    code blocks are left untouched."""
    body = body.replace("\r\n", "\n").replace("\r", "\n")
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    lines, fence = [], None
    for line in body.split("\n"):
        f = FENCE.match(line)
        if f:
            marker = f.group(1)
            if fence is None:
                fence = marker[0]
            elif marker[0] == fence:
                fence = None
            lines.append(line)
            continue
        if fence is not None:
            lines.append(line)
            continue
        h = ATX.match(line)
        if h:
            level = min(6, max(3, len(h.group(1)) + 1))
            lines.append("#" * level + " " + h.group(2))
            continue
        if DASHES.match(line):
            lines.append("***")
            continue
        if EQUALS.match(line):
            lines.append("")
            continue
        lines.append(line)
    return "\n".join(lines).strip("\n")


releases = [r for r in fetch_all() if not r.get("draft")]
keyed = [(semver_key(r["tag_name"]), r) for r in releases]
semver = sorted((k, r) for k, r in keyed if k is not None)
semver.reverse()
other = sorted((r for k, r in keyed if k is None), key=lambda r: r.get("published_at") or "", reverse=True)
ordered = [r for _, r in semver] + other
if not ordered:
    sys.exit(f"release-notes: no releases found for {repo}")

parts = [
    "---",
    "title: Release notes",
    f"description: Every Prague release newest first, generated from the GitHub Releases of {repo} at build time, with the changes each one carries.",
    "---",
    "",
    "<!-- Generated by www/docs/scripts/release-notes.sh from GitHub Releases. Do not edit; the file is gitignored. -->",
    "",
    "# Release notes",
    "",
    f"Every entry below is a [GitHub release of `{repo}`](https://github.com/{repo}/releases), listed newest first by "
    "semantic version. Stable versions are tagged `vX.Y.Z` and ship to [NuGet](https://www.nuget.org/packages/Prague/) as "
    "`Prague`, `Prague.Kafka`, `Prague.Api` and `Prague.Api.UI`; prereleases carry a `-pre.N` suffix (`vX.Y.Z-pre.N`), "
    "need `--prerelease` on `dotnet add package`, and sort below the stable version of the same base once it exists. "
    "A release is cut by the repository's Release workflow, which bumps the previous version (patch, minor or major) and "
    "lets GitHub write the notes from the merged pull requests. This page is regenerated on every docs build.",
    "",
]

for i, r in enumerate(ordered):
    tag = r["tag_name"]
    date = (r.get("published_at") or r.get("created_at") or "")[:10]
    heading = f"## {tag} — {date}" if date else f"## {tag}"
    if r.get("prerelease"):
        heading += " (prerelease)"
    parts.append(heading)
    parts.append("")
    # No synthetic "compare" link: the semver-previous tag is not always the git-previous
    # one (v0.6.1 was cut after v0.7.0-pre.2), and GitHub's own "Full Changelog" line in
    # the body already carries the correct compare URL.
    parts.append(f"[Release on GitHub]({r['html_url']})")
    parts.append("")
    body = demote(r.get("body") or "")
    parts.append(body if body else "_No release notes were written for this release._")
    parts.append("")

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(parts))
print(f"release-notes: wrote {len(ordered)} releases to {os.path.normpath(out)}")
PY
